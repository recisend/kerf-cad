// Builds lib/kernel.mjs from the web app's own sources so the MCP server and
// the browser app share one geometry kernel, sketch solver and feature set.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const src = (f) => readFileSync(join(here, '..', 'src', f), 'utf8');
let util = src('01-util.js').replace(/^import .*three\/addons.*\n/gm, '');
const body = [util, src('10-kernel.js'), src('15-formats.js'), src('20-sketch.js'), src('30-features.js')].join('\n');
const exportsList = [
  'THREE', 'V3', 'DEG', 'uid', 'deepClone', 'v3', 'arr3', 'fmt', 'evalExpr',
  'Solid', 'analyze', 'massProps', 'renderData', 'faceLoops', 'solidsToSTL', 'solidsToOBJ', 'solidsTo3MFParts', 'makeZip', 'exportModel', 'EXPORT_FORMATS', 'centroidOf',
  'newSketchData', 'skIndex', 'solveSketch', 'computeRegions', 'entPolyline', 'entPointIds', 'arcAngles', 'ORIGIN_ID', 'CONS_INFO', 'regionDepth', 'signedArea',
  'FEATURES', 'defaultParams', 'runFeature', 'newCtx', 'cloneCtx', 'resolveFace', 'resolveEdge', 'resolvePlane', 'resolveRegion', 'findPart', 'planeFromFace', 'toWorld', 'toPlane',
];
const out = `// GENERATED by build-kernel.mjs from ../src — do not edit by hand.\n${body}\nfunction resetFid() { FID = 1; }\nexport { ${exportsList.join(', ')}, resetFid };\n`;
writeFileSync(join(here, 'lib', 'kernel.mjs'), out);
console.log('wrote lib/kernel.mjs', out.length, 'bytes');
